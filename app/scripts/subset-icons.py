"""Builds src/icons/: Phosphor icon fonts cut down to the icons SafarCo uses.

The full fonts hold ~1,500 icons per weight (about 450 KB of CSS plus large fonts).
This keeps only the ph-* names found in src/, so the app loads far less on slow networks.

Run again after using a new icon:
    pip install fonttools brotli
    python3 scripts/subset-icons.py
"""
import pathlib, re, sys
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
PH = ROOT / 'node_modules/@phosphor-icons/web/src'
OUT = ROOT / 'src/icons'
WEIGHTS = {'fill': 'Fill', 'bold': 'Bold', 'duotone': 'Duotone'}
NOT_ICONS = {'ph-' + w for w in ['fill', 'bold', 'duotone', 'regular', 'thin', 'light']}

used = set()
for f in (ROOT / 'src').rglob('*'):
    if f.suffix in ('.ts', '.tsx') and 'icons' not in f.parts:
        used.update(m for m in re.findall(r'\bph-[a-z0-9]+(?:-[a-z0-9]+)*', f.read_text(encoding='utf-8')) if m not in NOT_ICONS)

OUT.mkdir(exist_ok=True)
css_out, missing = ['/* Generated by scripts/subset-icons.py. Do not edit by hand. */'], set(used)
for w, W in WEIGHTS.items():
    css = (PH / w / 'style.css').read_text(encoding='utf-8')
    base = re.search(r'\.ph-%s \{.*?\n\}' % w, css, re.S).group(0)
    rules, points = [], set()
    for name in sorted(used):
        for m in re.finditer(r'\.ph-%s\.%s:(?:before|after) \{[^}]*\}' % (w, re.escape(name)), css):
            rules.append(m.group(0)); missing.discard(name)
            points.update(int(c, 16) for c in re.findall(r'content: "\\([0-9a-f]+)"', m.group(0)))
    font = TTFont(PH / w / f'Phosphor-{W}.ttf')
    sub = subset.Subsetter(subset.Options(flavor='woff2', layout_features=['*'], name_IDs=['*'], notdef_outline=True))
    sub.populate(unicodes=points); sub.subset(font)
    font.flavor = 'woff2'; font.save(OUT / f'phosphor-{w}.woff2')
    css_out += [f'@font-face {{ font-family: "Phosphor-{W}"; src: url("./phosphor-{w}.woff2") format("woff2"); font-weight: normal; font-style: normal; font-display: block; }}', base, *rules]

(OUT / 'icons.css').write_text('\n'.join(css_out) + '\n', encoding='utf-8')
print(f'{len(used)} icons, {len(missing)} not found in Phosphor: {sorted(missing)}')
sys.exit(1 if missing else 0)
